"""
Исключения Camera Provider.

CameraOpenError  — не удалось открыть источник видеопотока.
CameraReadError  — не удалось получить кадр из открытого источника.

Не наследуются от RuntimeError — позволяет вызывающему коду
различать ошибки камеры и внутренние ошибки системы.
"""


class CameraOpenError(IOError):
    """Не удалось открыть источник видеопотока.

    Возникает при:
    - недоступном устройстве (device_index не существует);
    - провале теста чтения сразу после открытия;
    - любой другой ошибке инициализации.
    """


class CameraReadError(IOError):
    """Не удалось получить кадр из открытого источника.

    Возникает при критической ошибке чтения (не при пустом кадре —
    пустой кадр возвращается как None, а не исключение).
    """
