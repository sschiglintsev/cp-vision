"""
DecodedImage — внутреннее представление декодированного изображения.

Создаётся ImageDecoder один раз за запрос. Передаётся через этапы
Detection Pipeline без повторного декодирования из bytes.

Контракт: не изменять array и метаданные после создания.
Каждый запрос создаёт собственный экземпляр — смешивания данных между
параллельными запросами не происходит.
"""

from dataclasses import dataclass

import numpy as np


@dataclass
class DecodedImage:
    """Декодированное изображение: пиксельный массив и метаданные источника.

    Attributes:
        array:   RGB, shape (H, W, 3), dtype uint8. Не изменять после создания.
        width:   Ширина изображения в пикселях (из исходного файла).
        height:  Высота изображения в пикселях (из исходного файла).
        format:  Формат исходного файла в нижнем регистре: "jpeg", "png" и т.д.

    Потокобезопасность:
        Каждый запрос создаёт собственный DecodedImage через ImageDecoder.
        np.array() создаёт новый массив при каждом вызове — разделения
        данных между запросами не происходит.
    """

    array: np.ndarray  # RGB, shape (H, W, 3), dtype uint8
    width: int
    height: int
    format: str  # "jpeg", "png", ...
