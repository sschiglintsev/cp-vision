// ---------------------------------------------------------------------------
// Объект распознавания — поля не менять (CameraOverlay зависит от них)
// ---------------------------------------------------------------------------

export interface DetectedObject {
  class: string;
  confidence: number;
  x: number;         // абсолютные пиксели относительно исходного изображения
  y: number;
  width: number;
  height: number;
}

// ---------------------------------------------------------------------------
// Метаданные источника видеопотока
// ---------------------------------------------------------------------------

export type CameraSourceType = 'browser' | 'usb' | 'rtsp' | 'robot' | 'unknown';

export interface SourceMetadata {
  type: CameraSourceType;
  id: string | null;
  name: string | null;
}

// ---------------------------------------------------------------------------
// Метаданные изображения
// ---------------------------------------------------------------------------

export interface ImageMetadata {
  width: number;   // реальная ширина декодированного изображения в пикселях
  height: number;  // реальная высота декодированного изображения в пикселях
  format: string;  // "jpeg" | "png" | ...
}

// ---------------------------------------------------------------------------
// Метаданные модели инференса
// ---------------------------------------------------------------------------

export interface ModelMetadata {
  id: string;
  name: string;
  type: string;  // "object-detection" | "classification" | ...
}

// ---------------------------------------------------------------------------
// Универсальный результат распознавания
// Используется для будущей истории детекций, мультикамерной поддержки и т.д.
// ---------------------------------------------------------------------------

export interface DetectionResult {
  schemaVersion: string;
  cameraId: string | null;
  source: SourceMetadata;
  image: ImageMetadata;
  model: ModelMetadata;
  objects: DetectedObject[];
  timestamp: number;
}

// ---------------------------------------------------------------------------
// Вспомогательные типы
// ---------------------------------------------------------------------------

export interface ApiSuccessResponse<T> {
  success: true;
  data: T;
}
